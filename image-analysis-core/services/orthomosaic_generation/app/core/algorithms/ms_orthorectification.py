def _median_composite_band(
    image_paths: list[Path],
    output_path: Path,
    dsm_info: dict,
) -> None:
    """
    Fallback: create a median composite of reflectance images for one band.

    Used only when original source image paths are unavailable (so GPS-guided
    warping cannot be performed). All images are resized to the DSM pixel
    dimensions and blended by median — this produces correct CRS metadata but
    may exhibit horizontal banding for multi-strip surveys.

    Args:
        image_paths: Per-image reflectance TIFs
        output_path: Destination GeoTIFF
        dsm_info: DSM metadata (width, height, geotransform, projection)
    """
    if gdal is None:
        raise RuntimeError("GDAL Python bindings are required")

    arrays: list[np.ndarray] = []
    for p in image_paths:
        ds = gdal.Open(str(p), gdal.GA_ReadOnly)
        if ds is None:
            logger.warning(f"Cannot open {p}, skipping")
            continue
        arr = ds.GetRasterBand(1).ReadAsArray().astype(np.float32)
        arrays.append(arr)
        ds = None

    if not arrays:
        raise RuntimeError("No valid images to composite")

    target_h = dsm_info["height"]
    target_w = dsm_info["width"]

    resized: list[np.ndarray] = []
    for arr in arrays:
        if arr.shape == (target_h, target_w):
            resized.append(arr)
        else:
            from PIL import Image

            pil = Image.fromarray(arr)
            # Image.BILINEAR was removed in Pillow 10; use Resampling enum.
            resample = getattr(Image, "Resampling", Image).BILINEAR
            pil_resized = pil.resize((target_w, target_h), resample)
            resized.append(np.array(pil_resized, dtype=np.float32))

    stack = np.stack(resized, axis=0)
    median = np.median(stack, axis=0).astype(np.float32)

    # Clip to DSM field boundary — same as GPS composite path.
    coverage_mask = dsm_info.get("coverage_mask")
    if coverage_mask is not None:
        median = np.where(coverage_mask, median, _NODATA)

    driver = gdal.GetDriverByName("GTiff")
    out_ds = driver.Create(
        str(output_path),
        target_w,
        target_h,
        1,
        gdal.GDT_Float32,
        options=["COMPRESS=DEFLATE", "TILED=YES"],
    )
    out_ds.SetGeoTransform(dsm_info["geotransform"])
    out_ds.SetProjection(dsm_info["projection"])
    out_ds.GetRasterBand(1).WriteArray(median)
    out_ds.GetRasterBand(1).SetNoDataValue(_NODATA)
    out_ds.FlushCache()
    out_ds = None

    logger.info(
        f"Median composite written: {output_path} "
        f"({target_w}×{target_h}, float32)"
    )


def _read_dsm_metadata(dsm_path: Path) -> dict | None:
    """
    Read spatial metadata from the DSM GeoTIFF.

    Args:
        dsm_path: Path to DSM

    Returns:
        Dict with width, height, geotransform, projection (or None)
    """
    if gdal is None:
        raise RuntimeError("GDAL Python bindings are required")

    ds = gdal.Open(str(dsm_path), gdal.GA_ReadOnly)
    if ds is None:
        return None

    info = {
        "path": str(dsm_path),
        "width": ds.RasterXSize,
        "height": ds.RasterYSize,
        "geotransform": ds.GetGeoTransform(),
        "projection": ds.GetProjection(),
    }

    # Build a coverage mask: True where the DSM has valid (non-nodata) data.
    # This is used to clip band orthos to the actual field extent so the output
    # matches the RGB orthomosaic boundary instead of filling the whole bounding box.
    #
    # The mask is eroded by _DSM_MASK_EROSION_PX pixels before use so that the
    # noisy perimeter of the point cloud (sparse image overlap at field edges
    # causes COLMAP to produce artefacted depth estimates) is excluded.  The
    # erosion removes the radial streaking visible in hillshade and band outputs.
    try:
        band = ds.GetRasterBand(1)
        dsm_nd = band.GetNoDataValue()
        dsm_data = band.ReadAsArray()
        if dsm_nd is not None:
            coverage = (dsm_data != dsm_nd) & np.isfinite(dsm_data.astype(np.float32))
        else:
            coverage = np.isfinite(dsm_data.astype(np.float32))

        # Terrain elevation — median of valid DSM pixels before erosion.
        # Used by _extract_agl_and_hfov to convert AMSL GPS altitude to AGL.
        valid_elev = dsm_data[coverage].astype(np.float32)
        info["mean_elevation"] = float(np.median(valid_elev)) if valid_elev.size else 0.0

        try:
            from scipy.ndimage import binary_erosion
            coverage = binary_erosion(coverage, iterations=_DSM_MASK_EROSION_PX)
        except ImportError:
            logger.debug(
                "scipy not available — DSM coverage mask erosion skipped; "
                "perimeter reconstruction artefacts may appear in outputs"
            )
        info["coverage_mask"] = coverage
    except Exception:
        info["coverage_mask"] = None  # proceed without clipping if read fails
        info.setdefault("mean_elevation", 0.0)

    ds = None

    if not info["projection"]:
        logger.error(
            f"DSM at {dsm_path} has no CRS (empty projection). "
            "geo-registration (model_aligner) likely failed during SFM — "
            "geo_reference.json was not written. "
            "GPS-guided band orthorectification cannot proceed without a valid target SRS. "
            "Re-run the job after the geo_register fix is deployed."
        )
        return None

    return info


def _run_cmd(cmd: list[str], description: str) -> None:
    """
    Execute a shell command and raise on failure.

    Args:
        cmd: Command tokens
        description: Human-readable label for logging
    """
    logger.info(f"Running: {description}")
    logger.debug(f"Command: {' '.join(cmd)}")
    result = subprocess.run(cmd, check=True, capture_output=True, text=True)
    if result.stdout:
        logger.debug(f"stdout: {result.stdout[:500]}")
