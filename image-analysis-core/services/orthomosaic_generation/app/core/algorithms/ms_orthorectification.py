def _dms_to_decimal(dms: tuple, ref: str) -> float:
    """Convert degrees-minutes-seconds EXIF tuple to signed decimal degrees."""
    d, m, s = dms
    value = float(d) + float(m) / 60.0 + float(s) / 3600.0
    if ref in ("S", "W"):
        value = -value
    return value


def _extract_gps_from_image(path: Path) -> tuple[float, float, float] | None:
    """
    Extract (latitude, longitude, altitude_m) from image GPS EXIF.

    Returns None when GPS data is absent or cannot be parsed.
    """
    if _PILImage is None:
        return None
    try:
        with _PILImage.open(str(path)) as img:
            exif = img.getexif()
            if not exif:
                return None
            gps_ifd = exif.get_ifd(0x8825)  # GPS IFD tag
            if not gps_ifd:
                return None
            gps = {_GPSTAGS.get(k, k): v for k, v in gps_ifd.items()}

            lat_dms = gps.get("GPSLatitude")
            lon_dms = gps.get("GPSLongitude")
            if lat_dms is None or lon_dms is None:
                return None

            lat = _dms_to_decimal(lat_dms, gps.get("GPSLatitudeRef", "N"))
            lon = _dms_to_decimal(lon_dms, gps.get("GPSLongitudeRef", "E"))

            alt_tag = gps.get("GPSAltitude")
            alt_m = float(alt_tag) if alt_tag is not None else 100.0
            if gps.get("GPSAltitudeRef", 0) == 1:
                alt_m = -alt_m

            return lat, lon, alt_m
    except Exception as exc:
        logger.debug(f"GPS extraction failed for {path.name}: {exc}")
        return None


def _extract_agl_hfov_yaw(
    orig_path: Path,
    image_width: int,
    dsm_info: dict,
    drone_model: str | None = None,
) -> tuple[float, float, float]:
    """
    Return ``(agl_m, hfov_deg, yaw_deg)`` for a single image.

    **AGL resolution order** (critical — GPSAltitude is AMSL, not AGL):

    1. XMP ``drone-dji:RelativeAltitude`` — RTK AGL, most accurate.
    2. XMP ``drone-dji:AbsoluteAltitude`` minus ``dsm_info["mean_elevation"]``.
    3. EXIF ``GPSAltitude`` minus ``dsm_info["mean_elevation"]``.
    4. ``_DEFAULT_AGL_M`` (30 m).

    **HFOV resolution order**:

    1. XMP ``drone-dji:CalibratedFocalLength`` (pixels) + ``image_width``.
    2. EXIF ``FocalLength`` + ``FocalPlaneXResolution`` / ``FocalPlaneResolutionUnit``.
    3. EXIF ``FocalLengthIn35mmFilm``.
    4. ``_DRONE_MODEL_HFOV_DEG`` lookup keyed by ``drone_model``.
    5. ``_DEFAULT_HFOV_DEG`` (65°).

    **Yaw resolution order**:

    1. XMP ``drone-dji:FlightYawDegree`` — drone body heading.
    2. XMP ``drone-dji:GimbalYawDegree`` — gimbal yaw (fallback for fixed-mount sensors).
    3. 0.0 (north-up, no rotation).
    """
    agl_m: float | None = None
    hfov_deg: float | None = None
    yaw_deg: float = 0.0
    dsm_mean_elev: float = dsm_info.get("mean_elevation", 0.0)

    # ------------------------------------------------------------------
    # 1. XMP (highest priority for AGL, focal length, and yaw)
    # ------------------------------------------------------------------
    try:
        with open(orig_path, "rb") as fh:
            raw = fh.read()
        xmp_start = raw.find(b"<x:xmpmeta")
        xmp_end = raw.find(b"</x:xmpmeta>")
        if xmp_start != -1 and xmp_end != -1:
            xmp = raw[xmp_start : xmp_end + 12].decode("utf-8", errors="ignore")

            # AGL: RelativeAltitude is the most direct
            m = re.search(r'drone-dji:RelativeAltitude="([+-]?\d+\.?\d*)"', xmp)
            if m:
                agl_m = abs(float(m.group(1)))
                logger.debug(f"{orig_path.name}: AGL from XMP RelativeAltitude = {agl_m:.2f} m")

            # AGL fallback: AbsoluteAltitude minus terrain
            if agl_m is None:
                m = re.search(r'drone-dji:AbsoluteAltitude="([+-]?\d+\.?\d*)"', xmp)
                if m:
                    agl_m = abs(float(m.group(1))) - dsm_mean_elev
                    logger.debug(
                        f"{orig_path.name}: AGL from XMP AbsoluteAltitude - DSM mean "
                        f"= {agl_m:.2f} m"
                    )

            # HFOV: CalibratedFocalLength is in pixels — exact per-image value
            m = re.search(r'drone-dji:CalibratedFocalLength="([\d.]+)"', xmp)
            if m:
                fl_px = float(m.group(1))
                if fl_px > 0:
                    hfov_deg = math.degrees(2.0 * math.atan(image_width / (2.0 * fl_px)))
                    logger.debug(
                        f"{orig_path.name}: HFOV from XMP CalibratedFocalLength "
                        f"({fl_px:.1f} px) = {hfov_deg:.2f}°"
                    )

            # Yaw: FlightYawDegree is the drone body heading (clockwise from north).
            # GimbalYawDegree is used as fallback for fixed-mount multispectral sensors
            # where the gimbal yaw equals the flight heading.
            m = re.search(r'drone-dji:FlightYawDegree="([+-]?\d+\.?\d*)"', xmp)
            if m:
                yaw_deg = float(m.group(1))
                logger.debug(f"{orig_path.name}: yaw from XMP FlightYawDegree = {yaw_deg:.2f}°")
            else:
                m = re.search(r'drone-dji:GimbalYawDegree="([+-]?\d+\.?\d*)"', xmp)
                if m:
                    yaw_deg = float(m.group(1))
                    logger.debug(
                        f"{orig_path.name}: yaw from XMP GimbalYawDegree = {yaw_deg:.2f}°"
                    )
    except Exception as exc:
        logger.debug(f"XMP read failed for {orig_path.name}: {exc}")

    # ------------------------------------------------------------------
    # 2. EXIF fallbacks
    # ------------------------------------------------------------------
    if (agl_m is None or hfov_deg is None) and _PILImage is not None:
        try:
            with _PILImage.open(str(orig_path)) as img:
                exif = img.getexif()
                if exif:
                    # AGL: GPSAltitude is AMSL — subtract DSM terrain elevation
                    if agl_m is None:
                        gps_ifd = exif.get_ifd(0x8825)
                        alt_tag = gps_ifd.get(0x0006)  # GPSAltitude
                        if alt_tag is not None:
                            alt_amsl = float(alt_tag)
                            if gps_ifd.get(0x0005, 0) == 1:  # GPSAltitudeRef below sea
                                alt_amsl = -alt_amsl
                            agl_m = alt_amsl - dsm_mean_elev
                            logger.debug(
                                f"{orig_path.name}: AGL from EXIF GPSAltitude "
                                f"({alt_amsl:.1f} m AMSL) - DSM mean "
                                f"({dsm_mean_elev:.1f} m) = {agl_m:.2f} m"
                            )

                    if hfov_deg is None:
                        exif_ifd = exif.get_ifd(0x8769)  # Exif SubIFD

                        focal_raw = exif_ifd.get(0x920A)  # FocalLength
                        if focal_raw is not None:
                            focal_mm = float(focal_raw)
                            if focal_mm > 0:
                                fplane_res = exif_ifd.get(0xA20E)  # FocalPlaneXResolution
                                fplane_unit = exif_ifd.get(0xA210, 2)  # 2=inch, 3=cm
                                if fplane_res is not None:
                                    # DJI stores this as a rational tuple in some firmware
                                    if isinstance(fplane_res, tuple):
                                        fplane_res = fplane_res[0] / fplane_res[1]
                                    else:
                                        fplane_res = float(fplane_res)
                                    if fplane_res > 0:
                                        unit_mm = 25.4 if fplane_unit == 2 else 10.0
                                        pixel_pitch_mm = unit_mm / fplane_res
                                        sensor_width_mm = image_width * pixel_pitch_mm
                                        hfov_deg = math.degrees(
                                            2.0 * math.atan(
                                                sensor_width_mm / (2.0 * focal_mm)
                                            )
                                        )
                                        logger.debug(
                                            f"{orig_path.name}: HFOV from EXIF "
                                            f"focal+fplane = {hfov_deg:.2f}°"
                                        )

                        if hfov_deg is None:
                            f35_raw = exif_ifd.get(0xA405)  # FocalLengthIn35mmFilm
                            if f35_raw is not None and float(f35_raw) > 0:
                                hfov_deg = math.degrees(
                                    2.0 * math.atan(18.0 / float(f35_raw))
                                )
                                logger.debug(
                                    f"{orig_path.name}: HFOV from EXIF "
                                    f"35mm-equivalent = {hfov_deg:.2f}°"
                                )
        except Exception as exc:
            logger.debug(f"EXIF read failed for {orig_path.name}: {exc}")

    # ------------------------------------------------------------------
    # 3. Model lookup / hard defaults
    # ------------------------------------------------------------------
    if agl_m is None or agl_m <= 0:
        logger.debug(
            f"{orig_path.name}: AGL fallback to default {_DEFAULT_AGL_M} m "
            "(no XMP/EXIF altitude source)"
        )
        agl_m = _DEFAULT_AGL_M

    if hfov_deg is None:
        if drone_model and drone_model in _DRONE_MODEL_HFOV_DEG:
            hfov_deg = _DRONE_MODEL_HFOV_DEG[drone_model]
            logger.debug(
                f"{orig_path.name}: HFOV from drone model lookup "
                f"({drone_model}) = {hfov_deg:.2f}°"
            )
        else:
            logger.debug(
                f"{orig_path.name}: HFOV fallback to default {_DEFAULT_HFOV_DEG}°"
            )
            hfov_deg = _DEFAULT_HFOV_DEG

    return agl_m, hfov_deg, yaw_deg


def _build_original_image_map(
    band_manifest: dict,
    band_name: str,
) -> dict[str, str]:
    """
    Build a mapping from image stem → original file path.

    Uses the bands → {band_name} → images list in the serialised
    DatasetBandManifest dict passed from the API gateway.
    """
    if not band_manifest or not isinstance(band_manifest, dict):
        return {}

    band_group = band_manifest.get("bands", {}).get(band_name)
    if not isinstance(band_group, dict):
        return {}

    result: dict[str, str] = {}
    for img_info in band_group.get("images", []):
        file_path = (
            img_info.get("file_path", "")
            if isinstance(img_info, dict)
            else getattr(img_info, "file_path", "")
        )
        if file_path:
            result[Path(file_path).stem] = file_path
    return result


def orthorectify_bands(
    calibration_path: str,
    sfm_run_path: str,
    dsm_path: str,
    output_dir: str,
    band_manifest: dict | None = None,
) -> dict[str, str]:
    """
    Orthorectify all spectral bands onto the DSM grid.

    For each band, the calibrated reflectance images are projected onto the
    DSM's geographic grid and mosaiced into a single-band GeoTIFF.

    When ``band_manifest`` is supplied (normal production path), each image is
    GPS-positioned using EXIF from the original source file and warped to the
    target UTM grid with ``gdalwarp``.  Images are then composited using
    distance-weighted feathering: each pixel contribution is weighted by its
    distance from the nearest nodata/edge pixel, so overlapping images blend
    smoothly and flight-line seam artifacts are eliminated.

    When ``band_manifest`` is absent, a legacy median-composite fallback is
    used instead.

    Args:
        calibration_path: Root of calibrated images (contains band subfolders)
        sfm_run_path: SFM run directory (reserved for future pose-based ortho)
        dsm_path: Path to the filled DSM GeoTIFF
        output_dir: Directory for output band ortho GeoTIFFs
        band_manifest: Serialised DatasetBandManifest dict from the API gateway.
                       Required for GPS-guided warping.

    Returns:
        Mapping of band_name → output GeoTIFF path
    """
    cal_root = Path(calibration_path)
    out_root = Path(output_dir)
    out_root.mkdir(parents=True, exist_ok=True)

    dsm_info = _read_dsm_metadata(Path(dsm_path))
    if dsm_info is None:
        raise RuntimeError(f"Cannot read DSM metadata from {dsm_path}")

    # Pose-driven path (preferred): project each band through the SFM RGB poses + DSM
    # so all bands co-register by construction.  Falls back to the GPS path below
    # when disabled or when the SFM pose artifacts are unavailable.
    if _USE_POSE_ORTHO and band_manifest:
        logger.info("Orthorectifying bands via SFM poses (pose-driven path)")
        pose_outputs = orthorectify_bands_pose(
            calibration_path=calibration_path,
            sfm_run_path=sfm_run_path,
            dsm_info=dsm_info,
            band_manifest=band_manifest,
            output_dir=output_dir,
            bands=SPECTRAL_BANDS,
            build_original_map=_build_original_image_map,
        )
        if pose_outputs:
            return pose_outputs
        logger.warning(
            "Pose-driven orthorectification unavailable (no SFM geometry) — "
            "falling back to GPS-guided warping."
        )

    outputs: dict[str, str] = {}

    # Pass 1 — warp every band's images and record per-image mean + GPS.  Warped
    # TIFs are kept on disk (one tmp dir per band) until the blend pass.  Strip
    # normalisation gains are computed ACROSS all bands afterwards, never
    # per-band, so a common per-image illumination factor cancels in NDVI/NDRE/
    # GNDVI instead of being injected into them as flight-line banding.
    band_warps: dict[str, list[dict]] = {}
    band_tmp_dirs: dict[str, Path] = {}
    band_out_paths: dict[str, Path] = {}

    # Build the inter-band registration reference: one image per capture from a
    # reference band, keyed by capture sequence.  NIR is preferred (highest
    # vegetation contrast → most reliable phase correlation); fall back to the
    # first available band.  Each band is registered to this reference per
    # capture before warping so all bands share one ground footprint.
    reference_band = next(
        (b for b in ("nir", "red_edge", "red", "green") if (cal_root / b).is_dir()),
        None,
    )
    reference_map: dict[str, Path] = {}
    if reference_band is not None:
        ref_dir = cal_root / reference_band
        ref_tifs = sorted(ref_dir.glob("*_reflectance.tif")) or sorted(ref_dir.glob("*.tif"))
        reference_map = {_capture_key(p): p for p in ref_tifs}
        logger.info(
            f"Inter-band registration reference: {reference_band} "
            f"({len(reference_map)} captures)"
        )

    try:
        for band_name in SPECTRAL_BANDS:
            band_dir = cal_root / band_name
            if not band_dir.is_dir():
                logger.info(f"No calibrated images for band {band_name}, skipping")
                continue

            tifs = sorted(band_dir.glob("*_reflectance.tif"))
            if not tifs:
                tifs = sorted(band_dir.glob("*.tif"))
            if not tifs:
                logger.warning(f"No TIF files found in {band_dir}")
                continue

            original_map = _build_original_image_map(band_manifest, band_name)
            if not original_map:
                raise RuntimeError(
                    f"band_manifest missing original image paths for band '{band_name}'. "
                    "GPS-guided warping is required for correct multispectral alignment. "
                    "Ensure band_manifest is populated with source image file paths before "
                    "calling orthorectify_bands."
                )

            logger.info(
                f"Orthorectifying {len(tifs)} {band_name} images "
                f"({len(original_map)} original image paths available)"
            )

            # Keep warps on the output workspace volume (not /tmp): all bands'
            # warps are held until the shared-gain blend pass, which is more
            # temp data than the old per-band flow, and the job workspace has the
            # room the small system /tmp may not.
            tmp_dir = Path(tempfile.mkdtemp(prefix=f"ortho_gps_{band_name}_", dir=out_root))
            warped = _warp_band_images(
                tifs, dsm_info, original_map, tmp_dir, reference_map=reference_map,
            )
            if not warped:
                tmp_dir.rmdir()
                raise RuntimeError(
                    f"GPS composite failed for band '{band_name}': no images "
                    "could be warped. Check that original source image paths "
                    "are accessible and contain GPS EXIF."
                )

            band_warps[band_name] = warped
            band_tmp_dirs[band_name] = tmp_dir
            band_out_paths[band_name] = out_root / f"{band_name}_ortho.tif"

        if not band_warps:
            return outputs

        # Compute one shared per-image gain across all bands.  Strip identity is
        # geometric (band-independent); the gain corrects a single physical
        # per-pass illumination change that scales every band equally.
        all_stems: list[str] = []
        stem_latlon: dict[str, tuple[float, float]] = {}
        band_means: dict[str, dict[str, float]] = {}
        for band_name, warped in band_warps.items():
            band_means[band_name] = {it["stem"]: it["mean"] for it in warped}
            for it in warped:
                if it["stem"] not in stem_latlon:
                    stem_latlon[it["stem"]] = (it["lat"], it["lon"])
                    all_stems.append(it["stem"])

        lats = np.array([stem_latlon[s][0] for s in all_stems])
        lons = np.array([stem_latlon[s][1] for s in all_stems])
        gains_by_stem = _compute_shared_strip_gains(
            all_stems, lats, lons, band_means
        )

        # Pass 2 — apply the shared gains and feather-blend each band.
        for band_name, warped in band_warps.items():
            out_path = band_out_paths[band_name]
            _blend_band_with_gains(warped, gains_by_stem, out_path, dsm_info)
            outputs[band_name] = str(out_path)
            logger.info(f"Band {band_name} ortho: {out_path}")

    finally:
        for tmp_dir in band_tmp_dirs.values():
            for f in tmp_dir.glob("*.tif"):
                f.unlink(missing_ok=True)
            try:
                tmp_dir.rmdir()
            except OSError:
                pass  # non-empty on failure, leave for diagnosis

    return outputs


def stack_bands(
    band_paths: dict[str, str],
    output_path: str,
) -> str:
    """
    Stack single-band ortho GeoTIFFs into a multi-band GeoTIFF.

    Band order: Green, Red, RedEdge, NIR (bands 1-4).

    Args:
        band_paths: Mapping of band_name → single-band GeoTIFF path
        output_path: Destination for the stacked multi-band GeoTIFF

    Returns:
        Path to the stacked GeoTIFF
    """
    ordered = [
        band_paths[b] for b in SPECTRAL_BANDS if b in band_paths
    ]
    if not ordered:
        raise ValueError("No band orthos to stack")

    cmd = [
        "gdal_merge.py",
        "-separate",
        "-o", output_path,
        "-co", "COMPRESS=DEFLATE",
        "-co", "TILED=YES",
        "-co", "BIGTIFF=YES",
        "-ot", "Float32",
    ] + ordered

    logger.info(f"Stacking {len(ordered)} bands into {output_path}")
    _run_cmd(cmd, "band stacking")

    return output_path


