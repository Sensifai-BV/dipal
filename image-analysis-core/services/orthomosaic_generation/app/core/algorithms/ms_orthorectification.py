def _assign_flight_strips(
    lats: np.ndarray, lons: np.ndarray
) -> tuple[np.ndarray, int]:
    """
    Assign each image to a flight strip from its GPS coordinates.

    Flight strips are detected by projecting GPS coordinates onto the
    cross-track direction (found via PCA) and splitting at gaps that are large
    relative to the typical intra-strip cross-track step.

    Strip identity is a purely geometric property of the flight path and is
    therefore **band-independent** — the same image belongs to the same strip
    in every spectral band.  Keeping strip assignment separate from gain
    computation lets the caller derive a single per-image gain shared across
    all bands (see ``_compute_shared_strip_gains``), which is what preserves
    the ratio invariance of NDVI/NDRE/GNDVI.

    Args:
        lats: Per-image latitude (degrees)
        lons: Per-image longitude (degrees)

    Returns:
        Tuple of (strip_id array of length n, n_strips).  When fewer than two
        strips can be resolved, returns all-zero ids and ``n_strips == 1``.
    """
    n = len(lats)
    if n < 2:
        return np.zeros(n, dtype=int), 1

    cos_lat = np.cos(np.radians(lats.mean()))
    coords_m = np.column_stack([lats * 111320.0, lons * 111320.0 * cos_lat])

    centred = coords_m - coords_m.mean(axis=0)
    try:
        _, _, Vt = np.linalg.svd(centred, full_matrices=False)
    except np.linalg.LinAlgError:
        return np.zeros(n, dtype=int), 1
    cross_track_vec = Vt[1]           # second right-singular vector
    proj = centred @ cross_track_vec  # 1-D projection in metres

    sort_idx = np.argsort(proj)
    sorted_proj = proj[sort_idx]
    gaps = np.diff(sorted_proj)
    if len(gaps) == 0:
        return np.zeros(n, dtype=int), 1

    # Threshold is derived from the *typical* (intra-strip) cross-track gap, i.e.
    # the median of ALL gaps — which is dominated by the many small within-strip
    # steps, not the few large between-strip jumps.  A boundary is a gap that is
    # both ≥ 6× that typical step AND ≥ 5 m absolute.  Using the median of all
    # gaps (rather than only gaps > 0.5 m) avoids the failure mode where, with
    # low cross-track GPS jitter, the only surviving gaps are the between-strip
    # ones — which would make a "median × 3" threshold larger than the gaps
    # themselves and collapse everything into a single strip.
    typical_gap = float(np.median(gaps))
    gap_threshold = max(typical_gap * 6.0, 5.0)

    strip_ids_sorted = np.zeros(n, dtype=int)
    current_strip = 0
    for i, g in enumerate(gaps):
        if g > gap_threshold:
            current_strip += 1
        strip_ids_sorted[i + 1] = current_strip
    n_strips = current_strip + 1

    strip_id = np.empty(n, dtype=int)
    for rank, orig in enumerate(sort_idx):
        strip_id[orig] = strip_ids_sorted[rank]
    return strip_id, n_strips


def _compute_shared_strip_gains(
    stems: list[str],
    lats: np.ndarray,
    lons: np.ndarray,
    band_means: dict[str, dict[str, float]],
) -> dict[str, float]:
    """
    Compute one per-image gain shared across **all** bands.

    The historical bug behind the recurring NDVI flight-line banding was that a
    separate ``global_median / strip_mean`` gain was computed independently for
    each band.  Because the Red and NIR per-strip means differ, the per-band
    gains differed, and applying different multiplicative factors to Red and NIR
    changes the value of ``(NIR - Red) / (NIR + Red)`` — i.e. it injects banding
    straight into NDVI, which is supposed to be invariant to a *common*
    illumination factor.

    The fix: a flight strip is brighter or darker because of a single physical
    cause (sun-sensor / exposure for that pass), which scales *every* band by the
    same factor.  So we estimate one gain per strip from a band-averaged
    luminance and apply that identical gain to the image in every band.  A common
    factor cancels in every normalised-difference index, eliminating the banding
    while still flattening true strip-to-strip illumination steps.

    Args:
        stems: Per-image stem identifiers (band-independent image key)
        lats: Per-image latitude (degrees), aligned with ``stems``
        lons: Per-image longitude (degrees), aligned with ``stems``
        band_means: ``band_name → {stem → mean reflectance}`` from Pass 1 of
                    every band's warp

    Returns:
        Mapping of image stem → shared gain factor (1.0 = no correction)
    """
    n = len(stems)
    if n < 2:
        return {stem: 1.0 for stem in stems}

    strip_id, n_strips = _assign_flight_strips(lats, lons)
    if n_strips < 2:
        return {stem: 1.0 for stem in stems}

    # Band-averaged luminance per image: normalise each band by its own global
    # mean first so a bright band (NIR) does not dominate the average, then take
    # the mean of the available normalised band values for that image.
    band_global_mean: dict[str, float] = {}
    for band, per_stem in band_means.items():
        vals = [v for v in per_stem.values() if v > 0]
        band_global_mean[band] = float(np.mean(vals)) if vals else 0.0

    luminance = np.zeros(n, dtype=np.float64)
    for idx, stem in enumerate(stems):
        norm_vals = []
        for band, per_stem in band_means.items():
            g = band_global_mean.get(band, 0.0)
            v = per_stem.get(stem)
            if v is not None and v > 0 and g > 0:
                norm_vals.append(v / g)
        luminance[idx] = float(np.mean(norm_vals)) if norm_vals else 0.0

    strip_sum = np.zeros(n_strips, dtype=np.float64)
    strip_cnt = np.zeros(n_strips, dtype=int)
    for i in range(n):
        if luminance[i] > 0:
            strip_sum[strip_id[i]] += luminance[i]
            strip_cnt[strip_id[i]] += 1

    strip_means = np.where(strip_cnt > 0, strip_sum / np.maximum(strip_cnt, 1), 0.0)
    valid_mask = strip_cnt > 0
    if not valid_mask.any():
        return {stem: 1.0 for stem in stems}
    global_median = float(np.median(strip_means[valid_mask]))

    logger.info(
        f"Shared strip normalization (cross-band): {n_strips} strips, "
        f"luminance means {[round(float(m), 4) for m in strip_means[valid_mask]]}, "
        f"target median = {global_median:.4f}"
    )

    gains: dict[str, float] = {}
    for i, stem in enumerate(stems):
        sm = strip_means[strip_id[i]]
        gains[stem] = global_median / sm if sm > 0 else 1.0
    return gains


def _edge_distance_weight(valid: np.ndarray) -> np.ndarray:
    """
    Compute a smooth feathering weight for each valid pixel.

    For each valid pixel, returns the minimum of its distances (in pixel units)
    to the nearest invalid/nodata pixel in the four cardinal directions.  This
    produces a "tent" profile that peaks at image centres and fades to zero at
    image edges, enabling smooth blending when multiple images overlap.

    Implementation uses the "running-reset cumsum" trick — fully vectorised
    with NumPy, no scipy required.

    Args:
        valid: Boolean mask (True = valid pixel, False = nodata/invalid)

    Returns:
        Float32 weight array; 0 for invalid pixels, ≥ 1 for valid pixels.
    """
    v = valid.astype(np.int32)

    def _fwd_dist(arr2d: np.ndarray) -> np.ndarray:
        """Running distance to nearest 0 going left→right along axis=1."""
        cs = np.cumsum(arr2d, axis=1)
        # At each zero-position record the cumulative-sum value there,
        # then propagate it forward with a running maximum.
        baseline = np.where(arr2d == 0, cs, 0)
        np.maximum.accumulate(baseline, axis=1, out=baseline)
        return (cs - baseline) * arr2d

    left_d  = _fwd_dist(v)
    right_d = _fwd_dist(v[:, ::-1])[:, ::-1]
    top_d   = _fwd_dist(v.T).T
    bot_d   = _fwd_dist(v[::-1].T).T[::-1]

    return np.minimum(np.minimum(left_d, right_d),
                      np.minimum(top_d,  bot_d)).astype(np.float32)


def _phase_correlation_shift(
    ref: np.ndarray, mov: np.ndarray, max_shift_px: int = 40
) -> tuple[int, int]:
    """
    Estimate the integer (dy, dx) pixel shift that aligns ``mov`` onto ``ref``.

    Uses FFT phase correlation (numpy only — no OpenCV/scipy).  Both inputs are
    mean-removed so the DC term does not dominate.  The peak of the inverse FFT
    of the normalised cross-power spectrum gives the shift.  Shifts larger than
    ``max_shift_px`` are rejected (returns 0,0) as unreliable — the true
    inter-band offset on an M3M is a few px to ~15 px, so a large "shift" means
    the correlation peak is noise (e.g. near-empty overlap).

    Args:
        ref: Reference band array (e.g. NIR), same shape as ``mov``
        mov: Band array to be aligned to ``ref``
        max_shift_px: Reject/clamp shifts beyond this magnitude

    Returns:
        (dy, dx) integer shift to apply to ``mov`` (np.roll convention)
    """
    if ref.shape != mov.shape:
        return 0, 0
    a = np.nan_to_num(ref - float(np.nanmean(ref)))
    b = np.nan_to_num(mov - float(np.nanmean(mov)))
    F = np.fft.fft2(a)
    G = np.fft.fft2(b)
    R = F * np.conj(G)
    R /= np.abs(R) + 1e-12
    corr = np.fft.ifft2(R).real
    dy, dx = np.unravel_index(int(np.argmax(corr)), corr.shape)
    if dy > ref.shape[0] // 2:
        dy -= ref.shape[0]
    if dx > ref.shape[1] // 2:
        dx -= ref.shape[1]
    if abs(dy) > max_shift_px or abs(dx) > max_shift_px:
        return 0, 0
    return int(dy), int(dx)


def _warp_reflectance_image(
    refl_path: Path,
    orig_path: str,
    dsm_info: dict,
    warped_out: Path,
    tmp_dir: Path,
    gps: tuple[float, float, float] | None = None,
    reference_refl_path: Path | None = None,
) -> bool:
    """
    GPS-position a single reflectance TIFF and warp it to the target UTM grid.

    Steps:
      1. Extract GPS (lat, lon, alt) from the original source image (skipped
         when the caller already supplies ``gps``).
      2. Compute approximate GSD using altitude + assumed camera HFOV.
      3. Assign a WGS84 geotransform to the reflectance array and write a
         temporary GeoTIFF.
      4. Run gdalwarp to project into the target UTM CRS and grid extent.

    KNOWN LIMITATION — nadir assumption (camera tilt ignored).
        This is direct georeferencing: the image is placed at its GPS position
        and rotated only by *yaw* (``FlightYawDegree``).  Body **roll** and
        **pitch** are NOT applied, so the footprint is assumed perfectly nadir.
        On the DJI M3M the multispectral sensors are body-fixed (only the RGB
        camera is gimballed), so the MS bands actually tilt with the flight
        attitude — a ~10° roll at 12 m AGL shifts the footprint centre by
        ~2 m and skews it into a non-axis-aligned quad.  Correcting this needs a
        full collinearity / homography projection using
        ``FlightRollDegree`` + ``FlightPitchDegree`` (+ AGL), not a geotransform.
        Until then, residual per-image misregistration of up to a few GSD is
        expected on tilted captures; on gimbal-stabilised or low-wind flights
        the tilt is small.  See docs/changelogs for the rationale.

        Note also that this path uses raw EXIF GPS, NOT the PPK/MRK-upgraded
        positions used by the SFM geo-registration — another accuracy gap for
        the MS warp specifically.

    Args:
        gps: Pre-extracted (lat, lon, alt_m) tuple.  When supplied the
             internal EXIF read is skipped, saving one file open per image.

    Returns:
        True on success, False if GPS is unavailable or any step fails.
    """
    if gdal is None or osr is None:
        return False

    # --- 1. GPS ---
    if gps is None:
        gps = _extract_gps_from_image(Path(orig_path))
    if gps is None:
        logger.debug(f"No GPS for {Path(orig_path).name}, skipping")
        return False
    lat, lon, _alt_amsl = gps  # GPSAltitude is AMSL — AGL resolved below

    # --- 2. Source dimensions ---
    src_ds = gdal.Open(str(refl_path), gdal.GA_ReadOnly)
    if src_ds is None:
        return False
    src_w = src_ds.RasterXSize
    src_h = src_ds.RasterYSize
    data = src_ds.GetRasterBand(1).ReadAsArray().astype(np.float32)
    src_ds = None

    # --- 2b. Inter-band co-registration (per capture) ---
    # The M3M's spectral lenses are physically offset, so warping each band with
    # the same GPS/nadir geometry lands them at different ground positions
    # (measured constant ~(−12,−6) px offset).  Differencing misregistered bands
    # is the dominant source of vegetation-index noise.  Align this band to the
    # reference band (same capture) by an integer phase-correlation shift BEFORE
    # warping, so all bands of a capture share one footprint.  The reference band
    # registers against itself → zero shift (no-op).
    if reference_refl_path is not None and reference_refl_path != refl_path:
        ref_ds = gdal.Open(str(reference_refl_path), gdal.GA_ReadOnly)
        if ref_ds is not None:
            ref_data = ref_ds.GetRasterBand(1).ReadAsArray()
            ref_ds = None
            if ref_data is not None and ref_data.shape == data.shape:
                dy, dx = _phase_correlation_shift(
                    ref_data.astype(np.float32), data
                )
                if dy or dx:
                    # Shift band onto reference; vacated edges become nodata.
                    data = np.roll(np.roll(data, dy, axis=0), dx, axis=1)
                    if dy > 0:
                        data[:dy, :] = _NODATA
                    elif dy < 0:
                        data[dy:, :] = _NODATA
                    if dx > 0:
                        data[:, :dx] = _NODATA
                    elif dx < 0:
                        data[:, dx:] = _NODATA
                    logger.debug(
                        f"{refl_path.name}: band-registration shift "
                        f"dy={dy} dx={dx} px to reference {reference_refl_path.name}"
                    )

    # --- 3. AGL, HFOV, and yaw from XMP / EXIF / model lookup ---
    # GPSAltitude (EXIF) is AMSL.  For a field at ~90 m AMSL with the drone
    # at 95 m AMSL the true AGL is only ~5 m — using AMSL directly would give
    # an 8-19× error in computed footprint size.  _extract_agl_hfov_yaw reads
    # XMP RelativeAltitude first, then falls back to AMSL - DSM mean.
    agl_m, hfov_deg, yaw_deg = _extract_agl_hfov_yaw(Path(orig_path), src_w, dsm_info)
    hfov_rad = math.radians(hfov_deg)
    # Ground distance covered by the full image width
    ground_width_m = 2.0 * agl_m * math.tan(hfov_rad / 2.0)
    gsd_m = ground_width_m / src_w
    # Convert to degrees
    lat_rad = math.radians(lat)
    px_deg_x = gsd_m / (111320.0 * math.cos(lat_rad))
    px_deg_y = gsd_m / 111320.0

    # --- 4. Assign WGS84 geotransform with yaw rotation ---
    # GDAL geotransform rotation terms (gt[2], gt[4]) encode the image axes
    # in geographic space.  Without them every image is forced north-up,
    # misregistering footprints by up to several pixels at image corners when
    # the drone is not flying due north.  yaw_deg is clockwise from north.
    yaw_rad = math.radians(yaw_deg)
    cos_y = math.cos(yaw_rad)
    sin_y = math.sin(yaw_rad)
    # GDAL geotransform: X(col,row) = gt[0] + col*gt[1] + row*gt[2]
    #                    Y(col,row) = gt[3] + col*gt[4] + row*gt[5]
    # We want X(half_w, half_h) == lon, Y(half_w, half_h) == lat.
    # So:  ul_lon = lon - half_w*gt[1] - half_h*gt[2]
    #      ul_lat = lat - half_w*gt[4] - half_h*gt[5]
    half_w = src_w / 2.0
    half_h = src_h / 2.0
    gt1 =  px_deg_x * cos_y   # column step in longitude
    gt2 = -px_deg_y * sin_y   # row step in longitude    (rotation term)
    gt4 =  px_deg_x * sin_y   # column step in latitude  (rotation term)
    gt5 = -px_deg_y * cos_y   # row step in latitude
    ul_lon = lon - half_w * gt1 - half_h * gt2
    ul_lat = lat - half_w * gt4 - half_h * gt5
    src_gt = (ul_lon, gt1, gt2, ul_lat, gt4, gt5)

    geo_tif = tmp_dir / f"geo_{refl_path.stem}.tif"
    driver = gdal.GetDriverByName("GTiff")
    geo_ds = driver.Create(str(geo_tif), src_w, src_h, 1, gdal.GDT_Float32)
    geo_ds.SetGeoTransform(src_gt)
    epsg4326 = osr.SpatialReference()
    epsg4326.ImportFromEPSG(4326)
    geo_ds.SetProjection(epsg4326.ExportToWkt())
    band = geo_ds.GetRasterBand(1)
    band.WriteArray(data)
    band.SetNoDataValue(_NODATA)
    geo_ds.FlushCache()
    geo_ds = None

    # --- 5. gdalwarp to target UTM grid ---
    gt = dsm_info["geotransform"]
    xmin = gt[0]
    ymax = gt[3]
    xmax = xmin + dsm_info["width"] * gt[1]
    ymin = ymax + dsm_info["height"] * gt[5]  # gt[5] is negative
    res = abs(gt[1])

    cmd = [
        "gdalwarp",
        "-s_srs", "EPSG:4326",
        "-t_srs", dsm_info["projection"],
        "-te", str(xmin), str(ymin), str(xmax), str(ymax),
        "-tr", str(res), str(res),
        # Nearest-neighbour preserves the exact footprint boundary with no edge
        # erosion.  Bilinear + UNIFIED_SRC_NODATA erodes the valid footprint by
        # 1 px on every edge (the 2×2 kernel discards any pixel touching nodata),
        # producing the staircase outline visible around each image contribution.
        # Smooth blending is done by the distance-weighted feathering composite,
        # not by the per-image resampler.
        "-r", "near",
        "-srcnodata", str(_NODATA),
        "-dstnodata", str(_NODATA),
        "-wo", "UNIFIED_SRC_NODATA=YES",
        "-co", "COMPRESS=DEFLATE",
        str(geo_tif),
        str(warped_out),
    ]
    result = subprocess.run(cmd, capture_output=True, text=True)
    geo_tif.unlink(missing_ok=True)

    if result.returncode != 0:
        logger.warning(
            f"gdalwarp failed for {refl_path.name}: {result.stderr[:300]}"
        )
        return False
    return True


def _capture_key(refl_path: Path) -> str:
    """
    Return the DJI capture sequence key shared by all bands of one exposure.

    DJI multispectral filenames embed a 4-digit capture index, e.g.
    ``DJI_20240719091257_0001_MS_NIR_reflectance.tif`` → ``0001``.  All four
    bands of a capture share this key, so it links a band image to the reference
    band of the same exposure for inter-band registration.  Falls back to the
    full stem when the pattern is absent.
    """
    m = re.search(r"_(\d{4})_MS_", refl_path.name)
    return m.group(1) if m else refl_path.stem


def _warp_band_images(
    image_paths: list[Path],
    dsm_info: dict,
    original_image_map: dict[str, str],
    tmp_dir: Path,
    reference_map: dict[str, Path] | None = None,
) -> list[dict]:
    """
    Pass 1 of the GPS composite: GPS-warp every reflectance image of one band
    onto the DSM UTM grid and record its mean reflectance and GPS position.

    Warped TIFs are persisted in ``tmp_dir`` (one dir per band) so the blend
    pass can reload them after the shared cross-band gains have been computed.

    Args:
        image_paths: Calibrated reflectance TIFFs for one band
        dsm_info: DSM metadata (width, height, geotransform, projection)
        original_image_map: Mapping of image stem → original source file path
        tmp_dir: Directory in which warped TIFs are kept until the blend pass
        reference_map: Optional ``capture_key → reference-band reflectance path``
            (e.g. NIR per capture).  When given, each band image is phase-
            correlation-registered to its capture's reference band before warping
            so all bands share one ground footprint (fixes inter-band
            misregistration that otherwise corrupts vegetation indices).

    Returns:
        List of ``{path, stem, mean, lat, lon}`` dicts for the images that
        warped successfully with a positive mean reflectance.
    """
    if gdal is None:
        raise RuntimeError("GDAL Python bindings are required for GPS composite")

    warped_items: list[dict] = []
    skipped_nonpositive = 0

    for refl_path in image_paths:
        stem = refl_path.stem
        if stem.endswith("_reflectance"):
            stem = stem[: -len("_reflectance")]

        orig_path = original_image_map.get(stem)
        if not orig_path:
            logger.debug(
                f"No original image for {refl_path.name} (stem={stem!r}), skipping"
            )
            continue

        gps = _extract_gps_from_image(Path(orig_path))
        if gps is None:
            logger.debug(f"No GPS for {Path(orig_path).name}, skipping")
            continue
        gps_lat, gps_lon, _ = gps

        ref_refl = (
            reference_map.get(_capture_key(refl_path)) if reference_map else None
        )

        warped_out = tmp_dir / f"warped_{refl_path.stem}.tif"
        ok = _warp_reflectance_image(
            refl_path, orig_path, dsm_info, warped_out, tmp_dir, gps=gps,
            reference_refl_path=ref_refl,
        )
        if not ok or not warped_out.exists():
            continue

        warp_ds = gdal.Open(str(warped_out), gdal.GA_ReadOnly)
        if warp_ds is None:
            warped_out.unlink(missing_ok=True)
            continue
        data = warp_ds.GetRasterBand(1).ReadAsArray().astype(np.float32)
        warp_ds = None

        valid = (data != _NODATA) & np.isfinite(data)
        if not valid.any():
            warped_out.unlink(missing_ok=True)
            continue

        img_mean = float(data[valid].mean())
        if img_mean <= 0:
            warped_out.unlink(missing_ok=True)
            skipped_nonpositive += 1
            continue

        warped_items.append(
            {
                "path": warped_out,
                "stem": stem,
                "mean": img_mean,
                "lat": gps_lat,
                "lon": gps_lon,
            }
        )

    if skipped_nonpositive > 0:
        logger.warning(
            f"{skipped_nonpositive} image(s) had non-positive mean reflectance "
            "and were excluded from strip detection."
        )

    return warped_items


def _blend_band_with_gains(
    warped_items: list[dict],
    gains_by_stem: dict[str, float],
    output_path: Path,
    dsm_info: dict,
) -> None:
    """
    Pass 2 of the GPS composite: apply the shared per-image strip gain and
    feather-blend the warped images of one band into the final ortho.

    The gain applied to each image is looked up by stem from ``gains_by_stem``,
    which was computed **once across all bands** (see
    ``_compute_shared_strip_gains``).  Because the same image receives the same
    multiplicative factor in every band, the factor cancels in NDVI/NDRE/GNDVI
    and cannot introduce flight-line banding into the indices.

    Args:
        warped_items: Output of ``_warp_band_images`` for this band
        gains_by_stem: Shared image-stem → gain mapping (1.0 = no correction)
        output_path: Destination GeoTIFF
        dsm_info: DSM metadata (width, height, geotransform, projection, coverage_mask)
    """
    if gdal is None:
        raise RuntimeError("GDAL Python bindings are required for GPS composite")

    h = dsm_info["height"]
    w = dsm_info["width"]
    weighted_sum = np.zeros((h, w), dtype=np.float64)
    weight_total = np.zeros((h, w), dtype=np.float64)

    for item in warped_items:
        warp_ds = gdal.Open(str(item["path"]), gdal.GA_ReadOnly)
        if warp_ds is None:
            continue
        data = warp_ds.GetRasterBand(1).ReadAsArray().astype(np.float32)
        warp_ds = None
        item["path"].unlink(missing_ok=True)

        valid = (data != _NODATA) & np.isfinite(data)
        # Zero out nodata before multiplication so that isolated invalid pixels
        # (which receive a nonzero feathering weight from surrounding valid
        # pixels) cannot contribute -9999 into weighted_sum.
        data[~valid] = 0.0
        gain = np.float32(gains_by_stem.get(item["stem"], 1.0))
        data[valid] *= gain

        weight = _edge_distance_weight(valid)
        weighted_sum += data * weight
        weight_total += weight

    logger.info(
        f"Feather-blending {len(warped_items)} strip-normalised images → {output_path.name}"
    )

    with np.errstate(invalid="ignore", divide="ignore"):
        composite = np.where(
            weight_total > 0,
            (weighted_sum / weight_total).astype(np.float32),
            _NODATA,
        ).astype(np.float32)

    coverage_mask = dsm_info.get("coverage_mask")
    if coverage_mask is not None:
        composite = np.where(coverage_mask, composite, _NODATA)

    driver = gdal.GetDriverByName("GTiff")
    gt = dsm_info["geotransform"]
    out_ds = driver.Create(
        str(output_path), w, h, 1, gdal.GDT_Float32,
        options=["COMPRESS=DEFLATE", "TILED=YES", "BIGTIFF=YES"],
    )
    out_ds.SetGeoTransform(gt)
    out_ds.SetProjection(dsm_info["projection"])
    band_obj = out_ds.GetRasterBand(1)
    band_obj.WriteArray(composite)
    band_obj.SetNoDataValue(_NODATA)
    out_ds.FlushCache()
    out_ds = None


