"""
Multispectral band orthorectification using GPS and DSM geometry.

Orthorectifies calibrated reflectance images (per-band TIFs) onto the same
geographic grid as the RGB orthomosaic using:
  - Per-image GPS EXIF from the original source images
  - The DSM generated by the orthomosaic pipeline (for target CRS / extent)
  - GDAL gdalwarp for per-image geographic projection
  - gdal_merge for final mosaic with nodata-aware blending

Each reflectance image is placed at its correct GPS position (image centre)
and warped to the target UTM grid. This eliminates the horizontal banding
artifact that occurred when all images were naively resized to the full DSM
dimensions and blended without geographic positioning.
"""
from __future__ import annotations

import math
import os
import re
import subprocess
import tempfile
from pathlib import Path

import numpy as np

from services.orthomosaic_generation.app.core.algorithms.pose_ortho import (
    orthorectify_bands_pose,
)
from services.orthomosaic_generation.logger import logger

# Pose-driven orthorectification (project MS bands through the SFM RGB poses + DSM)
# replaces the GPS + nadir direct-georeferencing path, eliminating the "puzzle-piece"
# tile misplacement.  Opt-in until validated per dataset; auto-falls back to the GPS
# path when SFM pose artifacts are missing (e.g. non-SFM input).  See ADR 0002 §3.5.
_USE_POSE_ORTHO = os.environ.get("ORTHO_USE_POSE_ORTHO", "false").strip().lower() in (
    "1", "true", "yes",
)

try:
    from osgeo import gdal, osr

    gdal.UseExceptions()
except ImportError:
    gdal = None
    osr = None

try:
    from PIL import Image as _PILImage
    from PIL.ExifTags import GPSTAGS as _GPSTAGS
    from PIL.ExifTags import TAGS as _TAGS
except ImportError:
    _PILImage = None
    _TAGS = {}
    _GPSTAGS = {}

# AGL altitude used when no XMP/EXIF source is available.
# 30 m is a more conservative small-drone default than 100 m.
_DEFAULT_AGL_M: float = 30.0

# Horizontal FOV used as a last resort when all EXIF/XMP and model lookups fail.
# 65° is a rough mid-range value for small drone cameras.
_DEFAULT_HFOV_DEG: float = 65.0

# Known horizontal FOV per drone model, used when both EXIF and XMP lack focal data.
# Values are for the multispectral / main imaging sensor on each platform:
#   M3M  — DJI Mavic 3 Multispectral MS sensor, CalibratedFocalLength ≈3725 px @ 2592 px wide
#           → HFOV = 2·atan(2592/(2·3725)) ≈ 38.5°
#   P4M  — DJI Phantom 4 Multispectral, 5.74 mm lens, 1/2.9" sensor → HFOV ≈ 62.7°
_DRONE_MODEL_HFOV_DEG: dict[str, float] = {
    "M3M": 38.5,
    "M3T": 82.9,   # DJI Mavic 3 Thermal wide camera
    "M30": 79.0,   # DJI Matrice 30
    "P4M": 62.7,   # DJI Phantom 4 Multispectral
}

# NoData value written into intermediate warped TIFFs.
_NODATA: float = -9999.0

# Erosion applied to the DSM coverage mask before clipping band outputs.
# Removes the noisy perimeter of the reconstruction (sparse point cloud at
# field edges) which otherwise causes radial streaking in hillshade outputs.
# Units: pixels.  Increase if boundary artefacts are still visible.
_DSM_MASK_EROSION_PX: int = 15


SPECTRAL_BANDS = ["blue", "green", "red", "red_edge", "nir"]


